def _norm_str(val) -> str:
    """字符串归一化：去空白、去除时间后缀"""
    if val is None:
        return ""
    s = str(val).strip()
    if s.endswith(" 00:00:00"):
        s = s[:-9]
    return s


def _norm_code(val) -> str:
    """信用代码归一化：去空白、转大写"""
    return re.sub(r"\s+", "", _norm_str(val)).upper()


def _format_amount(val) -> str:
    """金额格式化：保留两位小数，每千位逗号分隔"""
    try:
        return "{:,.2f}".format(float(val))
    except (ValueError, TypeError):
        return "0.00"


