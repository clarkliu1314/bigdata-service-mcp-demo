@mcp.tool()
def query_fund_investments(fund_name: str) -> str:
    """
    查询基金对外投资情况。

    通过基金简称查询该合伙企业的对外投资明细，用于核对：
    - 投资标的企业的全称、统一社会信用代码
    - 累计投资本金额是否匹配

    Args:
        fund_name: 基金简称（支持模糊匹配）

    Returns:
        JSON 格式的投资明细列表

        如果未查询到数据，返回空列表 []
    """
    if not fund_name:
        return "[]"

    # 模糊匹配基金简称
    for key, records in _MOCK_FUND_INVESTMENTS.items():
        if key in fund_name:
            result = []
            for r in records:
                result.append({
                    "被投企业全称": r.get("被投企业全称", ""),
                    "统一社会信用代码": r.get("统一社会信用代码", ""),
                    "累计投资本金额": _format_amount(r.get("累计投资本金额", 0))
                })
            return str(result)

    return "[]"


@mcp.tool()
def query_company_business(credit_code: str) -> str:
    """
    查询企业工商信息。

    通过统一社会信用代码查询企业工商登记信息

    Args:
        credit_code: 统一社会信用代码

    Returns:
        JSON 格式的工商信息对象
        如果未查询到数据，返回 null
    """
    if not credit_code:
        return "null"

    normalized = _norm_code(credit_code)
    biz_info = _MOCK_BIZ_DB.get(normalized)

    if biz_info:
        return str(biz_info)

    return "null"


@mcp.tool()
def batch_query_companies(credit_codes: str) -> str:
    """
    批量查询企业工商信息。

    Args:
        credit_codes: 逗号分隔的信用代码列表
                      例如："91411500MAG0YUAK0N,913604055892302382"

    Returns:
        JSON 格式的结果列表
    """
    if not credit_codes:
        return "[]"

    codes = [c.strip() for c in credit_codes.split(",") if c.strip()]
    results = []

    for code in codes:
        normalized = _norm_code(code)
        biz_info = _MOCK_BIZ_DB.get(normalized)
        results.append({
            "credit_code": code,
            "data": biz_info
        })

    return str(results)


